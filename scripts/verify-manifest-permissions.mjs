#!/usr/bin/env node
/**
 * Irodora — the permission set is checked on every pull request, not only at a tag (F-114).
 *
 * ## The gap this closes, and the one it does not
 *
 * Gate 16 reads the built APK and is the only thing that catches a dependency shipping a
 * permission (E-049). It runs in `release.yml` because **there is no APK on a pull request** —
 * which is correct, and which means the delay between introducing a permission and learning
 * about it is a tag. F-043 added `expo-image-picker` and `RECORD_AUDIO`; five features closed
 * before a signed artefact said so.
 *
 * `expo prebuild` already runs inside gate 6 and writes
 * `apps/mobile/android/app/src/main/AndroidManifest.xml`. That file is exactly what
 * `app.config.ts` and its plugins contribute — including which permissions carry
 * `tools:node="remove"` — so a config plugin that adds one is visible **on the pull request**,
 * with no Gradle, no JDK and no emulator.
 *
 * ## THIS IS NOT GATE 16, and the difference is the whole reason to say so
 *
 * **A green result here does not mean the shipped APK holds only these permissions.** This reads
 * a manifest; gate 16 reads an artefact. Three permissions in the real APK appear in **no file
 * this check reads**:
 *
 *     android.permission.USE_BIOMETRIC                     expo-local-authentication's manifest
 *     android.permission.USE_FINGERPRINT                   the same
 *     …DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION            AndroidX, from the prebuild template
 *
 * They arrive at Gradle time, from AARs in a cache, and nothing short of a build sees them. So
 * this catches the **config-plugin half** of E-049 and not the library-manifest half, and it
 * prints the names it cannot see on every run — a check that let anybody believe otherwise would
 * be worse than no check. **Gate 16 stays exactly as it is.**
 *
 * ## The declared list is derived, never copied
 *
 * `verify-apk.mjs` owns `EXPECTED_PERMISSIONS`, and its own comment records why: the list *"used
 * to be a workflow argument duplicated in two files, and keeping two copies of a
 * security-relevant set in agreement is not a thing to rely on a person for."* A second copy here
 * would repeat that exactly.
 *
 * So the subtraction runs the other way: what this expects is the artefact's list **minus** the
 * ones that arrive at Gradle time. Adding a permission to gate 16's expectation therefore changes
 * what this expects too, unless somebody declares it invisible — and declaring it invisible is a
 * deliberate act with a name and a reason beside it.
 *
 * Usage:
 *   node scripts/verify-manifest-permissions.mjs
 *   node scripts/verify-manifest-permissions.mjs --prove   # watch every assertion fail
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ciError } from './annotate.mjs';
import { EXPECTED_PERMISSIONS } from './verify-apk.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = 'apps/mobile/android/app/src/main/AndroidManifest.xml';

const GREEN = '\x1b[32m',
  RED = '\x1b[31m',
  YELLOW = '\x1b[33m',
  DIM = '\x1b[2m',
  BOLD = '\x1b[1m',
  OFF = '\x1b[0m';

/**
 * The permissions in the shipped APK that reach it **after** this file is written.
 *
 * This is the only list here, and it is criterion 3 expressed as data rather than as a sentence:
 * every name in it is a thing this check is blind to, so the set it expects is
 * `EXPECTED_PERMISSIONS` minus these. A permission added to gate 16's list and not to this one
 * becomes something this check starts requiring — which is the right default, because the
 * exception is what needs justifying.
 */
const MERGED_AT_GRADLE_TIME = new Map([
  ['android.permission.USE_BIOMETRIC', "expo-local-authentication's own library manifest"],
  ['android.permission.USE_FINGERPRINT', "expo-local-authentication's own library manifest"],
  [
    'com.irodora.app.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION',
    'generated by AndroidX from the prebuild template; in no dependency and no source file',
  ],
]);

/** What `app.config.ts` and its plugins must contribute, derived rather than restated. */
const fromConfig = () => new Set(EXPECTED_PERMISSIONS.filter((p) => !MERGED_AT_GRADLE_TIME.has(p)));

/**
 * Every `<uses-permission>` in a manifest, split by whether the config keeps or removes it.
 *
 * A regular expression rather than an XML parser, and the reason is the same one that keeps this
 * package dependency-free: the shape being read is one element with two attributes, written by a
 * generator, and a parser would be a dependency inside a security-relevant check. The pattern is
 * anchored on the element name so a permission mentioned in a comment is not a declaration.
 */
export function readPermissions(xml) {
  const kept = new Set();
  const removed = new Set();

  for (const m of xml.matchAll(/<uses-permission\b([^>]*)\/?>/gu)) {
    const attrs = m[1] ?? '';
    const name = /android:name\s*=\s*"([^"]+)"/u.exec(attrs)?.[1];
    if (name === undefined) continue;
    // `tools:node="remove"` is how a config strips a permission a plugin asked for. A
    // permission that carries it is a REFUSAL, and reading it as a declaration would report
    // every removal as a capability.
    if (/tools:node\s*=\s*"remove"/u.test(attrs)) removed.add(name);
    else kept.add(name);
  }

  return { kept, removed };
}

/** The findings for one manifest. Empty means green. */
export function checkManifest(xml) {
  const problems = [];
  const { kept, removed } = readPermissions(xml);
  const expected = fromConfig();

  for (const name of kept)
    if (!expected.has(name))
      problems.push({
        kind: name === 'android.permission.INTERNET' ? 'internet' : 'unexpected',
        name,
        detail:
          name === 'android.permission.INTERNET'
            ? 'INTERNET is in the prebuilt manifest WITHOUT tools:node="remove". NFR-12 is a ' +
              'claim about the network, and this falsifies it before any artefact exists.'
            : 'A permission the configuration contributes that nobody reviewed. Either it is ' +
              'wanted — add it to EXPECTED_PERMISSIONS in verify-apk.mjs, which is the one ' +
              'owner of that list — or the plugin that asked for it needs tools:node="remove".',
      });

  for (const name of expected)
    if (!kept.has(name))
      problems.push({
        kind: 'missing',
        name,
        detail:
          'Expected from the configuration and absent from the prebuilt manifest. A missing ' +
          'permission is a feature that fails on a device with nothing at build time to say so.',
      });

  /*
   * INTERNET has to be REMOVED, not merely absent. An absent line and a `tools:node="remove"`
   * line are different facts: the second survives a library manifest asking for it, and the
   * first does not. NFR-12 is a claim about the shipped app, so it is the removal that carries
   * it.
   */
  if (!removed.has('android.permission.INTERNET') && !kept.has('android.permission.INTERNET'))
    problems.push({
      kind: 'internet',
      name: 'android.permission.INTERNET',
      detail:
        'Neither declared nor removed. `tools:node="remove"` is what survives a library ' +
        'manifest asking for INTERNET; an absent line does not, and the merger adds silently ' +
        'and by design.',
    });

  return { problems, kept, removed };
}

function report(xml) {
  const { problems, kept, removed } = checkManifest(xml);

  console.log(`\n${BOLD}Prebuilt manifest — permissions${OFF}\n`);
  console.log(
    `${DIM}  ${String(kept.size)} kept · ${String(removed.size)} removed by config${OFF}`,
  );
  console.log(`${DIM}  kept: ${[...kept].sort().join(', ')}${OFF}`);

  // Printed on EVERY run, green included. A limit nobody reads is a limit nobody weighs.
  console.log(
    `\n  ${YELLOW}!${OFF} ${DIM}NOT CHECKED HERE — reaches the APK after this file is written:${OFF}`,
  );
  for (const [name, why] of MERGED_AT_GRADLE_TIME)
    console.log(`${DIM}      ${name} — ${why}${OFF}`);
  console.log(
    `${DIM}      This is not gate 16. It reads a manifest, not an artefact, and cannot see what\n` +
      `      library manifests merge in. A green result here is not a claim about the APK.${OFF}`,
  );

  if (problems.length > 0) {
    console.log('');
    for (const p of problems) {
      console.log(`  ${RED}✗${OFF} ${BOLD}${p.name}${OFF} ${DIM}(${p.kind})${OFF}`);
      console.log(`${DIM}      ${p.detail}${OFF}`);
      ciError(`permission: ${p.name}`, p.detail);
    }
    console.log(
      `\n${RED}${BOLD}Permission check FAILED.${OFF} ${String(problems.length)} finding(s).\n`,
    );
    return 1;
  }

  console.log(`\n${GREEN}${BOLD}Permission set matches the configuration.${OFF}\n`);
  return 0;
}

/**
 * The manifest to read.
 *
 * `--manifest` exists for one reason: the absent-manifest case in `--prove` has to be a real
 * assertion. Renaming the actual file mid-proof would leave a build artefact moved if the proof
 * threw, and an `existsSync` on a path nobody created asserts nothing at all — which is a
 * decoration wearing a tick.
 */
const manifestArg = process.argv.indexOf('--manifest');
const manifestPath =
  manifestArg >= 0 && process.argv[manifestArg + 1] !== undefined
    ? resolve(ROOT, process.argv[manifestArg + 1])
    : resolve(ROOT, MANIFEST);

if (process.argv.includes('--prove')) {
  if (!existsSync(manifestPath)) {
    console.log(`${RED}${MANIFEST} is absent — run \`pnpm build\` first.${OFF}`);
    process.exit(1);
  }
  const real = readFileSync(manifestPath, 'utf8');

  console.log(`\n${BOLD}Proving the permission check discriminates${OFF}\n`);

  const cases = [
    ['the real manifest', real, false],
    /*
     * F-043's ACTUAL EPISODE, replayed. expo-image-picker asked for RECORD_AUDIO and the
     * removal marker is what keeps it out; drop the marker and this is the pull request that
     * would have said so five features earlier.
     */
    [
      'RECORD_AUDIO no longer removed',
      real.replace(
        /<uses-permission android:name="android\.permission\.RECORD_AUDIO" tools:node="remove"\/>/u,
        '<uses-permission android:name="android.permission.RECORD_AUDIO"/>',
      ),
      true,
    ],
    [
      'INTERNET no longer removed',
      real.replace(
        /<uses-permission android:name="android\.permission\.INTERNET" tools:node="remove"\/>/u,
        '<uses-permission android:name="android.permission.INTERNET"/>',
      ),
      true,
    ],
    [
      'INTERNET neither declared nor removed',
      real.replace(
        /\s*<uses-permission android:name="android\.permission\.INTERNET" tools:node="remove"\/>/u,
        '',
      ),
      true,
    ],
    [
      'CAMERA removed from the configuration',
      real.replace(/\s*<uses-permission android:name="android\.permission\.CAMERA"\/>/u, ''),
      true,
    ],
    [
      'a permission mentioned only in a comment is not a declaration',
      real.replace(
        '<queries>',
        '<!-- android.permission.RECORD_AUDIO is discussed here and not declared -->\n  <queries>',
      ),
      false,
    ],
  ];

  let bad = 0;
  for (const [name, xml, shouldFail] of cases) {
    if (xml === real && shouldFail) {
      console.log(`  ${RED}✗${OFF} ${name} — the plant changed nothing, so it proves nothing`);
      bad += 1;
      continue;
    }
    const failed = checkManifest(xml).problems.length > 0;
    const ok = failed === shouldFail;
    if (!ok) bad += 1;
    console.log(
      `  ${ok ? GREEN + '✓' : RED + '✗'}${OFF} ${failed ? 'RED  ' : 'GREEN'} ${DIM}${name}${OFF}`,
    );
  }

  /*
   * THE ABSENT-MANIFEST CASE, RUN FOR REAL. `prebuild` not having run is exactly the state this
   * check must not be quiet about — it is the one in which a green result means nobody looked.
   *
   * Asserted by SPAWNING the script against a path that does not exist and reading its exit
   * code, because the decision lives in the runner rather than in `checkManifest`. The first
   * draft of this case called `existsSync` on a made-up path and printed a tick, which asserted
   * nothing whatever about the check.
   */
  let absentExit = 0;
  try {
    execFileSync(
      process.execPath,
      [fileURLToPath(import.meta.url), '--manifest', 'apps/mobile/android/__absent__.xml'],
      { cwd: ROOT, stdio: 'pipe' },
    );
  } catch (e) {
    absentExit = e.status ?? 1;
  }
  const absentOk = absentExit !== 0;
  if (!absentOk) bad += 1;
  console.log(
    `  ${absentOk ? GREEN + '✓' : RED + '✗'}${OFF} RED   ${DIM}an absent manifest fails, rather than passing with nothing to read${OFF}`,
  );

  if (bad > 0) {
    console.log(`\n${RED}${BOLD}The check does not discriminate.${OFF} ${String(bad)} case(s).\n`);
    process.exit(1);
  }
  console.log(
    `\n${GREEN}${BOLD}Check proven.${OFF} ${DIM}A permission that loses its removal marker is ` +
      `named, one mentioned in a comment is not, and the real manifest is green either side.${OFF}\n`,
  );
  process.exit(0);
}

if (!existsSync(manifestPath)) {
  const detail =
    `${MANIFEST} does not exist. It is written by \`expo prebuild\`, which runs inside gate 6 ` +
    '(`pnpm build`) — so this step belongs after it. Passing with nothing to read would be the ' +
    'one failure this check cannot afford: a green result meaning nobody looked.';
  console.log(`\n${RED}${BOLD}Permission check FAILED.${OFF} ${DIM}${detail}${OFF}\n`);
  ciError('permission: no prebuilt manifest', detail);
  process.exit(1);
}

process.exit(report(readFileSync(manifestPath, 'utf8')));
